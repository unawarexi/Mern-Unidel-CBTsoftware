export const generateReport = async (req, res) => {
  try {
    const {
      type,
      title,
      contextId,
      filters = {},
      formats = ["pdf"],
    } = req.body;

    const isPublic = PUBLIC_REPORT_TYPES.includes(type);

    if (!isPublic && !req.user) {
      console.warn(`[REPORT] Unauthorized access attempt for type: ${type}`);
      return res
        .status(401)
        .json({ message: "Authentication required for this report type" });
    }

    const userId = req.user?._id || null;
    const userRole = req.user?.role || "public";
    const userModel = userId
      ? userRole.charAt(0).toUpperCase() + userRole.slice(1)
      : null;

    // Fetch branding
    const branding = await getBranding();

    // Route to appropriate handler
    let reportData;

    switch (type) {
      // Student Reports
      case "exam-history":
        reportData = await handleExamHistory(userId, contextId, branding);
        break;
      case "semester-results":
      case "semester-summary":
        reportData = await handleSemesterResults(userId, filters, branding);
        break;
      case "transcript":
        reportData = await handleTranscript(userId, branding);
        break;
      case "account-summary":
      case "account-report":
        reportData = await handleAccountSummary(userId, userRole, branding);
        break;

      // Lecturer Reports
      case "course-performance":
        reportData = await handleCoursePerformance(userId, contextId, branding);
        break;
      case "exam-results":
      case "exam-analysis":
        reportData = await handleExamAnalysis(contextId, branding);
        break;
      case "student-roster":
        reportData = await handleStudentRoster(userId, contextId, branding);
        break;

      // Admin Reports
      case "system-overview":
        reportData = await handleSystemOverview(branding);
        break;
      case "user-management":
        reportData = await handleUserManagement(filters, branding);
        break;
      case "department-summary":
        reportData = await handleDepartmentSummary(branding);
        break;
      case "faculty-summary":
        reportData = await handleFacultySummary(branding);
        break;

      // Public Reports
      case "faculties-report":
        reportData = await handleFacultiesReport(branding);
        break;
      case "fees-report":
        reportData = await handleFeesReport(branding);
        break;
      case "events-report":
        reportData = await handleEventsReport(branding);
        break;
      case "scholarships-report":
        reportData = await handleScholarshipsReport(branding);
        break;
      case "careers-report":
        reportData = await handleCareersReport(branding);
        break;

      default:
        return res
          .status(400)
          .json({ message: `Unknown report type: ${type}` });
    }

    // Generate and upload files
    const links = await generateAndUpload(
      reportData.data,
      reportData.columns,
      reportData.title,
      reportData.subtitle,
      formats,
      type,
      reportData.options,
    );

    // Save to database (only for authenticated users)
    let report = null;
    if (userId) {
      report = new Report({
        userId,
        userModel,
        title: reportData.title,
        type,
        contextId,
        filters,
        links,
      });
      await report.save();
    }

    res.status(201).json({
      message: "Report generated successfully",
      report,
      links,
    });
  } catch (error) {
    console.error("[REPORT] Error generating report:", error);
    res
      .status(500)
      .json({ message: error.message || "Failed to generate report" });
  }
};

