const handleExamHistory = async (userId, contextId, branding) => {
  // Get submission with full exam and course details
  const submission = await Submission.findOne({
    _id: contextId,
    studentId: userId,
  }).populate({
    path: "examId",
    populate: [
      { path: "courseId", select: "courseCode courseTitle" },
      { path: "lecturerId", select: "fullname email" },
    ],
  });

  if (!submission) throw new Error("Submission not found");

  const exam = submission.examId;
  const course = exam?.courseId;
  const lecturer = exam?.lecturerId;

  // Build question-by-question analysis
  const questionData = exam.questions.map((q, idx) => {
    const studentAnswer =
      submission.answers.find((a) => a.questionId === q._id?.toString())
        ?.answer || "No Answer";
    const isCorrect = studentAnswer === q.correctAnswer;
    return {
      questionNumber: idx + 1,
      question: q.question,
      options: q.options.join(", "),
      studentAnswer,
      correctAnswer: q.correctAnswer,
      isCorrect,
      marks: isCorrect ? q.marks : 0,
      maxMarks: q.marks,
    };
  });

  // Summary stats
  const correctCount = questionData.filter((q) => q.isCorrect).length;

  // Summary stats for PDF
  const pdfSummary = [
    {
      label: "Course",
      value: `${course?.courseCode} - ${course?.courseTitle}`,
    },
    { label: "Lecturer", value: lecturer?.fullname || "N/A" },
    {
      label: "Date",
      value: new Date(submission.submittedAt).toLocaleDateString(),
    },
    {
      label: "Score",
      value: `${submission.score}/${submission.totalMarks}`,
      class: submission.passed ? "success" : "danger",
    },
    {
      label: "Status",
      value: submission.passed ? "PASSED" : "FAILED",
      class: submission.passed ? "success" : "danger",
    },
  ];

  const pdfStats = [
    { label: "Questions", value: exam.questions.length },
    { label: "Correct", value: correctCount, class: "success" },
    {
      label: "Wrong",
      value: exam.questions.length - correctCount,
      class: "danger",
    },
    {
      label: "Percentage",
      value: `${submission.percentage}%`,
      class: "primary",
    },
  ];

  const pdfQuestions = questionData.map((q) => ({
    number: q.questionNumber,
    text: q.question,
    studentAnswer: q.studentAnswer,
    correctAnswer: q.correctAnswer,
    isCorrect: q.isCorrect,
    marks: q.marks,
    maxMarks: q.maxMarks,
  }));

  // Table data (simplified for main table)
  const data = questionData.map((q) => ({
    question: `Q${q.questionNumber}`,
    yourAnswer: q.studentAnswer,
    correctAnswer: q.correctAnswer,
    result: q.isCorrect ? "Correct" : "Incorrect",
    marks: `${q.marks}/${q.maxMarks}`,
  }));

  const columns = [
    { header: "#", key: "question" },
    { header: "Your Answer", key: "yourAnswer" },
    { header: "Correct Answer", key: "correctAnswer" },
    { header: "Result", key: "result" },
    { header: "Marks", key: "marks" },
  ];

  return {
    data,
    columns,
    title: `Exam History: ${course?.courseCode}`,
    subtitle: `${course?.courseTitle} | ${new Date(submission.submittedAt).toLocaleDateString()}`,
    options: {
      branding,
      summary: pdfSummary,
      pdfData: {
        DOCUMENT_TITLE: "Exam History Report",
        DOCUMENT_SUBTITLE: `${course?.courseCode} | ${student?.fullname}`,
        SUMMARY: pdfSummary,
        STATS: pdfStats,
        QUESTIONS: pdfQuestions,
      },
      showQuestionAnalysis: true,
      questionData,
    },
  };
};

