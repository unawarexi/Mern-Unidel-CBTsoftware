const handleCoursePerformance = async (userId, contextId, branding) => {
  const courseId = contextId;
  const course = await Course.findById(courseId);
  if (!course) throw new Error("Course not found");

  const exams = await Exam.find({ courseId });
  const examIds = exams.map((e) => e._id);

  const submissions = await Submission.find({
    examId: { $in: examIds },
    status: "graded",
  });

  // Calculate stats per exam
  const data = await Promise.all(
    exams.map(async (exam) => {
      const examSubs = submissions.filter(
        (s) => s.examId.toString() === exam._id.toString(),
      );
      const avgScore =
        examSubs.length > 0
          ? (
              examSubs.reduce((sum, s) => sum + s.percentage, 0) /
              examSubs.length
            ).toFixed(1)
          : 0;
      const passCount = examSubs.filter((s) => s.passed).length;

      return {
        examDate: new Date(exam.startTime).toLocaleDateString(),
        duration: `${exam.duration} mins`,
        totalStudents: examSubs.length,
        averageScore: `${avgScore}%`,
        passRate:
          examSubs.length > 0
            ? `${((passCount / examSubs.length) * 100).toFixed(1)}%`
            : "N/A",
        highestScore:
          examSubs.length > 0
            ? `${Math.max(...examSubs.map((s) => s.percentage))}%`
            : "N/A",
        lowestScore:
          examSubs.length > 0
            ? `${Math.min(...examSubs.map((s) => s.percentage))}%`
            : "N/A",
      };
    }),
  );

  const columns = [
    { header: "Exam Date", key: "examDate" },
    { header: "Duration", key: "duration" },
    { header: "Students", key: "totalStudents" },
    { header: "Avg Score", key: "averageScore" },
    { header: "Pass Rate", key: "passRate" },
    { header: "Highest", key: "highestScore" },
    { header: "Lowest", key: "lowestScore" },
  ];

  const summary = {
    courseCode: course.courseCode,
    courseTitle: course.courseTitle,
    totalExams: exams.length,
    totalSubmissions: submissions.length,
  };

  return {
    data,
    columns,
    title: `Course Performance: ${course.courseCode}`,
    subtitle: course.courseTitle,
    options: { branding, summary },
  };
};

