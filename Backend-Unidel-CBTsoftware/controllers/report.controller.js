const generateAndUpload = async (
  data,
  columns,
  title,
  subtitle,
  formats,
  type,
  options = {},
) => {
  const links = {};
  const timestamp = Date.now();

  for (const format of formats) {
    let buffer;
    const filename = `${type}_${timestamp}.${format}`;

    if (format === "pdf") {
      // Check if we have specialized data for PDF
      if (options.pdfData) {
        buffer = await pdfRenderer.generatePDFFromTemplate({
          templateName: options.templateName || "pdf-base",
          data: options.pdfData,
          branding: options.branding,
        });
      } else {
        // Fallback to table-based PDF
        buffer = await pdfRenderer.generateTablePDF({
          title,
          subtitle,
          data,
          columns,
          summary: options.summary,
          infoBox: options.infoBox,
          branding: options.branding,
          showSignature: options.showSignature,
        });
      }
    } else if (format === "csv") {
      buffer = generateCSV(data, columns);
    } else if (format === "xlsx") {
      buffer = generateXLSX(data, columns);
    } else if (format === "docx") {
      buffer = await generateDOCX(data, columns, title, subtitle, options);
    }

    if (buffer) {
      const uploadResult = await uploadToCloudinary(
        buffer,
        filename,
        `reports/${type}`,
      );
      links[format] = uploadResult.url;
    }
  }

  return links;
};

